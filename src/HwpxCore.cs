        private static void AppendTextPayload(StringBuilder xml, string text)
        {
            string normalized = (text ?? string.Empty).Replace("\r\n", "\n").Replace('\r', '\n');
            if (normalized.Length == 0)
            {
                xml.Append("<hp:t/>");
                return;
            }

            StringBuilder chunk = new StringBuilder();
            for (int i = 0; i < normalized.Length; i++)
            {
                char ch = normalized[i];
                if (ch == '\n' || ch == '\t')
                {
                    if (chunk.Length > 0)
                    {
                        xml.Append("<hp:t>");
                        xml.Append(Escape(chunk.ToString()));
                        xml.Append("</hp:t>");
                        chunk.Length = 0;
                    }
                    xml.Append(ch == '\n' ? "<hp:lineBreak/>" : "<hp:tab/>");
                }
                else
                {
                    chunk.Append(ch);
                }
            }

            if (chunk.Length > 0)
            {
                xml.Append("<hp:t>");
                xml.Append(Escape(chunk.ToString()));
                xml.Append("</hp:t>");
            }
        }

        private static string BuildPreviewText(TextDocument document)
        {
            StringBuilder text = new StringBuilder();
            for (int p = 0; p < document.Paragraphs.Count; p++)
            {
                if (p > 0)
                    text.AppendLine();
                DocumentParagraph paragraph = document.Paragraphs[p];
                if (paragraph != null)
                    text.Append(paragraph.PlainText ?? string.Empty);
            }
            return text.ToString();
        }

        private static void WriteEntry(
            ZipArchive archive,
            string path,
            string content,
            CompressionLevel compression)
        {
            ZipArchiveEntry entry = archive.CreateEntry(path, compression);
            using (Stream stream = entry.Open())
            using (StreamWriter writer = new StreamWriter(stream, new UTF8Encoding(false)))
                writer.Write(content ?? string.Empty);
        }

        private static void ReplaceSafely(string stage, string destination, string backup)
        {
            if (!File.Exists(destination))
            {
                File.Move(stage, destination);
                return;
            }

            File.Move(destination, backup);
            try
            {
                File.Move(stage, destination);
                DeleteIfExists(backup);
            }
            catch
            {
                try
                {
                    DeleteIfExists(destination);
                    if (File.Exists(backup))
                        File.Move(backup, destination);
                }
                catch { }
                throw;
            }
        }

        private static void DeleteIfExists(string path)
        {
            try
            {
                if (File.Exists(path))
                    File.Delete(path);
            }
            catch { }
        }

        private static string NormalizeColor(string value)
        {
            string text = (value ?? string.Empty).Trim().TrimStart('#').ToUpperInvariant();
            int parsed;
            if (text.Length == 6 && int.TryParse(text, NumberStyles.HexNumber, CultureInfo.InvariantCulture, out parsed))
                return text;
            return "20242A";
        }

        private static string Escape(string value)
        {
            return SecurityElement.Escape(value ?? string.Empty) ?? string.Empty;
        }
