        private static string BuildSectionXml(TextDocument document, StyleCatalog catalog)
        {
            StringBuilder xml = new StringBuilder();
            xml.Append("<?xml version=\"1.0\" encoding=\"UTF-8\"?>");
            xml.Append("<hs:sec xmlns:hp=\"http://www.hancom.co.kr/hwpml/2011/paragraph\" xmlns:hs=\"http://www.hancom.co.kr/hwpml/2011/section\">");
            xml.Append(BuildSectionPropertyParagraph());

            int paragraphId = 1000000002;
            for (int p = 0; p < document.Paragraphs.Count; p++)
            {
                DocumentParagraph paragraph = document.Paragraphs[p];
                if (paragraph == null)
                    continue;

                xml.Append("<hp:p id=\"");
                xml.Append(paragraphId.ToString(CultureInfo.InvariantCulture));
                paragraphId++;
                xml.Append("\" paraPrIDRef=\"");
                xml.Append(((int)paragraph.Alignment).ToString(CultureInfo.InvariantCulture));
                xml.Append("\" styleIDRef=\"0\" pageBreak=\"0\" columnBreak=\"0\" merged=\"0\">");

                if (paragraph.Runs.Count == 0)
                {
                    xml.Append("<hp:run charPrIDRef=\"0\"><hp:t/></hp:run>");
                }
                else
                {
                    for (int r = 0; r < paragraph.Runs.Count; r++)
                    {
                        DocumentTextRun run = paragraph.Runs[r];
                        if (run == null)
                            continue;
                        string family = string.IsNullOrEmpty(run.FontFamily) ? "Arial" : run.FontFamily;
                        CharStyleKey style = CreateStyle(run, family);
                        int styleId;
                        if (!catalog.CharStyleIds.TryGetValue(style.Key, out styleId))
                            styleId = 0;

                        xml.Append("<hp:run charPrIDRef=\"");
                        xml.Append(styleId.ToString(CultureInfo.InvariantCulture));
                        xml.Append("\">");
                        AppendTextPayload(xml, run.Text ?? string.Empty);
                        xml.Append("</hp:run>");
                    }
                }

                xml.Append("</hp:p>");
            }

            if (document.Paragraphs.Count == 0)
                xml.Append("<hp:p id=\"1000000002\" paraPrIDRef=\"0\" styleIDRef=\"0\" pageBreak=\"0\" columnBreak=\"0\" merged=\"0\"><hp:run charPrIDRef=\"0\"><hp:t/></hp:run></hp:p>");

            xml.Append("</hs:sec>");
            return xml.ToString();
        }

